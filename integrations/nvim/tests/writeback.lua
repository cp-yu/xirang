local root = assert(vim.env.XIRANG_TEST_PROJECT)
local repo = assert(vim.env.XIRANG_TEST_REPO)
local cli = { assert(vim.env.XIRANG_TEST_NODE), vim.fs.joinpath(repo, 'bin', 'xirang.js') }
local review = dofile(vim.fs.joinpath(repo, 'integrations', 'nvim', 'lua', 'xirang', 'review.lua'))
review.setup({ cwd = root, cli = cli })
vim.cmd('XirangReview demo')
local function waitFor(predicate)
  assert(vim.wait(10000, predicate, 10), '等待真实 CLI 响应超时')
end
local session
waitFor(function()
  session = review._sessions[vim.api.nvim_get_current_tabpage()]
  return session and session.items and #session.items > 0
end)
vim.api.nvim_set_current_win(session.rightWin)
local original = table.concat(vim.api.nvim_buf_get_lines(session.right, 0, -1, false), '\n')
assert(original:find('planned text', 1, true))
local edited = original:gsub('planned text', 'saved text'):gsub('title: item', 'title: ignored title')
vim.api.nvim_buf_set_lines(session.right, 0, -1, false, vim.split(edited, '\n', { plain = true }))
vim.api.nvim_win_set_cursor(session.rightWin, { 5, 2 })
vim.cmd('write')
waitFor(function() return not session.saving and not vim.bo[session.right].modified end)
local result = table.concat(vim.api.nvim_buf_get_lines(session.right, 0, -1, false), '\n')
assert(result:find('saved text', 1, true))
assert(not result:find('ignored title', 1, true))
assert(vim.wo[session.rightWin].statusline:find('title', 1, true))
assert(vim.api.nvim_get_current_win() == session.rightWin)
assert(vim.api.nvim_win_get_cursor(session.rightWin)[1] == 5)
assert(not vim.bo[session.left].modifiable and vim.bo[session.right].modifiable)
local source = vim.fs.joinpath(root, '.xirang', 'changes', 'demo', 'elements', 'item.md')
local bytes = table.concat(vim.fn.readfile(source), '\n')
assert(bytes:find('saved text', 1, true))
assert(not bytes:find('ignored title', 1, true))
local invalid = result:gsub('Item SHALL have saved text.', 'invalid text')
vim.api.nvim_buf_set_lines(session.right, 0, -1, false, vim.split(invalid, '\n', { plain = true }))
vim.cmd('write')
waitFor(function() return session.saveError ~= nil end)
assert(table.concat(vim.api.nvim_buf_get_lines(session.right, 0, -1, false), '\n') == invalid)
assert(vim.bo[session.right].modified)
assert(table.concat(vim.fn.readfile(source), '\n') == bytes)
review.closeCurrent()
vim.cmd('qa!')
